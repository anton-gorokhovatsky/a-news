// A bound phrase moves as a whole when it fits. A narrow line can break at its space.
function markExternalLinks() {
  for (const label of document.querySelectorAll("[data-external-label]")) {
    if (label.closest("a[href]")?.origin === location.origin) {
      label.removeAttribute("data-external-label");
      continue;
    }
    const text = label.textContent.trimEnd();
    const lastGlyph = /[^\s\p{M}]\p{M}*$/u.exec(text);
    if (!lastGlyph) continue;

    const ending = document.createElement("span");
    ending.className = "external-link-ending";
    ending.textContent = lastGlyph[0];
    ending.insertAdjacentHTML("beforeend", externalLinkMark);

    if (!label.closest("h2, h3")) {
      label.replaceChildren(text.slice(0, lastGlyph.index), ending);
      continue;
    }

    const boundPhrase = /[^\s]+(?:\u00a0[^\s]+)+$/u.exec(text);
    const phraseStart = boundPhrase?.index ?? lastGlyph.index;
    label.replaceChildren();

    for (const part of text.slice(0, phraseStart).split(/( +)/u)) {
      if (part.includes("\u00ad")) {
        const word = document.createElement("span");
        word.className = "wrap-group headline-wrap";
        word.textContent = part;
        label.append(word);
      } else {
        label.append(part);
      }
    }

    if (boundPhrase) {
      const phrase = document.createElement("span");
      phrase.className = "wrap-group headline-wrap";
      phrase.append(text.slice(phraseStart, lastGlyph.index).replaceAll("\u00a0", " "), ending);
      label.append(phrase);
    } else {
      label.append(ending);
    }
  }
}
